#!/usr/bin/env bash
# Regenerates extern/core-math from CORE-MATH at the pinned commit. See docs/determinism-math.md.
#
#   tools/revendor-core-math.sh           fetch the pin, copy the four files, apply
#                                         extern/core-math/patches/*.patch, write NOTES.md
#   tools/revendor-core-math.sh --check   regenerate into a temp dir and diff against the
#                                         tree; exit 1 on drift; writes nothing in the repo
#   tools/revendor-core-math.sh --prove   build unpatched upstream and the patched files on
#                                         the MSVC fallback paths (patches/core_math_compat.h
#                                         forced) with gcc, and compare every output; exit 1
#                                         on any difference; writes nothing in the repo
#
# The vendored tree is generated by this script, never hand-edited.

set -euo pipefail

URL=https://gitlab.inria.fr/core-math/core-math.git
SHA=cac142bc65dc140d645ba3f79511a9c591d1746e
FILES="src/binary32/atan2/atan2f.c src/binary32/sin/sinf.c src/binary32/cos/cosf.c LICENSE"

ROOT=$(cd "$(dirname "$0")/.." && pwd)
DEST=$ROOT/extern/core-math
PATCHES=$DEST/patches

MODE=write
case "${1:-}" in
	"") ;;
	--check) MODE=check ;;
	--prove) MODE=prove ;;
	*) echo "usage: $0 [--check|--prove]" >&2; exit 2 ;;
esac

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Shallow partial fetch of the one sha (blobs fetched only for the four files), full fetch as fallback.
fetch() {
	local dir=$TMP/upstream
	git init -q "$dir"
	if ! git -C "$dir" fetch -q --depth 1 --filter=blob:none "$URL" "$SHA" 2>/dev/null; then
		echo "shallow fetch of $SHA failed, falling back to a full fetch" >&2
		git -C "$dir" fetch -q "$URL"
	fi
	# shellcheck disable=SC2086
	git -C "$dir" checkout -q "$SHA" -- $FILES
	git -C "$dir" log -1 --format=%cI "$SHA" > "$TMP/commit-date"
}

# The vendored tree: the four files flat, then each patch in name order.
generate() {
	local out=$1 f p
	mkdir -p "$out"
	for f in $FILES; do
		cp "$TMP/upstream/$f" "$out/$(basename "$f")"
	done
	for p in "$PATCHES"/*.patch; do
		[ -e "$p" ] || continue
		patch -s -p1 -d "$out" < "$p"
	done
	notes > "$out/NOTES.md"
}

sha() {
	sha256sum "$1" | cut -d' ' -f1
}

notes() {
	local f b p
	echo "# CORE-MATH, vendored"
	echo
	echo "Generated by tools/revendor-core-math.sh; never hand-edited. Policy: docs/determinism-math.md."
	echo
	echo "- repository: $URL"
	echo "- commit: $SHA"
	echo "- commit date: $(cat "$TMP/commit-date")"
	echo "- license: MIT, LICENSE vendored as fetched; it carries no copyright line, the copyright lines are in each source file:"
	for f in $FILES; do
		case "$f" in *.c)
			echo "  - $(basename "$f"): $(grep -m1 '^Copyright' "$TMP/upstream/$f")" ;;
		esac
	done
	echo
	echo "| file | upstream path | sha256 as fetched | sha256 as vendored |"
	echo "|---|---|---|---|"
	for f in $FILES; do
		b=$(basename "$f")
		echo "| $b | $f | $(sha "$TMP/upstream/$f") | $(sha "$out/$b") |"
	done
	echo
	echo "## Patches"
	echo
	echo "Applied in name order from patches/ with patch -p1. patches/core_math_compat.h is force-included"
	echo "into the three files on MSVC cl only (src/CMakeLists.txt); it maps the GCC builtins to the C99"
	echo "functions and defines the macros the patches read. tools/revendor-core-math.sh --prove builds the"
	echo "patched files on those fallback paths with gcc and compares them to unpatched CORE-MATH."
	echo
	for p in "$PATCHES"/*.patch; do
		[ -e "$p" ] || continue
		echo "- $(basename "$p") (sha256 $(sha "$p")):"
		sed -n '/^--- /q;p' "$p" | sed '/^$/d; s/^/  /'
	done
}

prove() {
	local up=$TMP/up pa=$TMP/pa b
	mkdir -p "$up" "$pa"
	for f in $FILES; do
		case "$f" in *.c) cp "$TMP/upstream/$f" "$up/" ;; esac
	done
	generate "$pa"
	local cc=${CC:-gcc} flags="-O2 -ffp-contract=off -w -c"
	for b in atan2f sinf cosf; do
		$cc $flags -Dcr_$b=up_$b -o "$TMP/up_$b.o" "$up/$b.c"
		$cc $flags -Dcr_$b=pa_$b -DB3_CORE_MATH_COMPAT_FORCE=1 -include "$PATCHES/core_math_compat.h" \
			-o "$TMP/pa_$b.o" "$pa/$b.c"
	done
	cat > "$TMP/prove.c" <<'PROVE'
#include <inttypes.h>
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
float up_atan2f( float, float ), pa_atan2f( float, float );
float up_sinf( float ), pa_sinf( float ), up_cosf( float ), pa_cosf( float );
static uint32_t bits( float x ) { uint32_t u; memcpy( &u, &x, 4 ); return u; }
static float flt( uint32_t u ) { float x; memcpy( &x, &u, 4 ); return x; }
// equal bit patterns, or NaN on both sides
static int same( float a, float b ) { return bits( a ) == bits( b ) || ( isnan( a ) && isnan( b ) ); }
int main( void )
{
	uint64_t bad = 0, n1 = 0, n2 = 0;
	for ( uint64_t u = 0; u < ( 1ull << 32 ); ++u )
	{
		float x = flt( (uint32_t)u );
		bad += !same( up_sinf( x ), pa_sinf( x ) );
		bad += !same( up_cosf( x ), pa_cosf( x ) );
		n1 += 1;
	}
	uint64_t s = 0x9E3779B97F4A7C15ull;
	for ( uint64_t i = 0; i < ( 1ull << 28 ); ++i )
	{
		s ^= s << 13; s ^= s >> 7; s ^= s << 17;
		float y = flt( (uint32_t)( s >> 32 ) ), x = flt( (uint32_t)s );
		bad += !same( up_atan2f( y, x ), pa_atan2f( y, x ) );
		n2 += 1;
	}
	printf( "core-math prove sinf,cosf inputs=%" PRIu64 " each atan2f inputs=%" PRIu64 " differ=%" PRIu64 "\n", n1, n2, bad );
	return bad != 0;
}
PROVE
	$cc -O2 -o "$TMP/prove" "$TMP/prove.c" "$TMP"/up_*.o "$TMP"/pa_*.o -lm
	"$TMP/prove"
}

fetch

case $MODE in
	write)
		generate "$TMP/out"
		for f in $FILES; do
			cp "$TMP/out/$(basename "$f")" "$DEST/"
		done
		cp "$TMP/out/NOTES.md" "$DEST/"
		echo "extern/core-math regenerated at $SHA"
		;;
	check)
		generate "$TMP/out"
		if diff -r -x patches "$TMP/out" "$DEST"; then
			echo "extern/core-math matches $SHA plus patches"
		else
			echo "extern/core-math drifted from $SHA plus patches" >&2
			exit 1
		fi
		;;
	prove)
		prove
		;;
esac
